/**
 * Clipboard Utilities for Chess-Sensei
 *
 * Provides rich clipboard functionality for:
 * - Copying game analysis as formatted HTML
 * - Copying move history with styling
 * - Sharing annotated games
 *
 * Uses Neutralino 6.0.0+ clipboard.writeHTML() API
 * @see https://neutralino.js.org/docs/api/clipboard/
 */

import { clipboard } from '@neutralinojs/lib';
import { frontendLogger } from './frontend-logger';

