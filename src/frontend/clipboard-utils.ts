/**
 * Copy analysis report to clipboard as HTML
 */
export async function copyAnalysisAsHTML(): Promise<void> {
  try {
    frontendLogger.info('Clipboard', 'Copying analysis as HTML');

    const analysisOverlay = document.getElementById('analysis-overlay');
    if (!analysisOverlay || analysisOverlay.classList.contains('hidden')) {
      // eslint-disable-next-line no-alert
      alert('No analysis to copy. Please open an analysis first.');
      return;
    }

    // Generate HTML
    const html = generateAnalysisHTML(null);

    // Copy to clipboard
    await clipboard.writeHTML(html);

    frontendLogger.info('Clipboard', 'Analysis copied to clipboard as HTML');
    showCopyNotification('Analysis copied to clipboard!');
  } catch (error) {
    frontendLogger.error('Clipboard', 'Failed to copy analysis:', error);

    // Fallback to plain text copy
    try {
      const analysisText = document.getElementById('analysis-content')?.innerText || '';
      await navigator.clipboard.writeText(analysisText);
      showCopyNotification('Analysis copied as plain text (HTML not supported)');
    } catch (_fallbackError) {
      // eslint-disable-next-line no-alert
      alert('Failed to copy analysis to clipboard.');
    }
  }
}

/**
 * Copy move history to clipboard as HTML
 */
export async function copyMoveHistoryAsHTML(): Promise<void> {
  const moveList = document.getElementById('move-list');
  if (!moveList || !moveList.textContent?.trim()) {
    // eslint-disable-next-line no-alert
    alert('No moves to copy. Play some moves first.');
    return;
  }

  try {
    frontendLogger.info('Clipboard', 'Copying move history as HTML');

    // Generate HTML
    const html = generateMoveHistoryHTML();

    // Copy to clipboard
    await clipboard.writeHTML(html);

    frontendLogger.info('Clipboard', 'Move history copied to clipboard as HTML');
    showCopyNotification('Move history copied to clipboard!');
  } catch (error) {
    frontendLogger.error('Clipboard', 'Failed to copy move history:', error);

    // Fallback to plain text
    try {
      const moveText = moveList.innerText || '';
      await navigator.clipboard.writeText(moveText);
      showCopyNotification('Move history copied as plain text');
    } catch (_fallbackError) {
      // eslint-disable-next-line no-alert
      alert('Failed to copy move history to clipboard.');
    }
  }
}

/**
 * Show a temporary notification that content was copied
 */
function showCopyNotification(message: string): void {
  // Create notification element
  const notification = document.createElement('div');
  notification.className = 'copy-notification';
  notification.textContent = `✓ ${message}`;
  notification.style.cssText = `
    position: fixed;
    top: 20px;
    right: 20px;
    background: #27ae60;
    color: white;
    padding: 15px 20px;
    border-radius: 5px;
    box-shadow: 0 4px 6px rgba(0,0,0,0.2);
    z-index: 10000;
    animation: slideIn 0.3s ease-out;
  `;

  document.body.appendChild(notification);

  // Remove after 3 seconds
  setTimeout(() => {
    notification.style.animation = 'slideOut 0.3s ease-in';
    setTimeout(() => notification.remove(), 300);
  }, 3000);
}

/**
 * Add CSS animations for notifications
 */
if (typeof window !== 'undefined') {
  const style = document.createElement('style');
  style.textContent = `
    @keyframes slideIn {
      from {
        transform: translateX(400px);
        opacity: 0;
      }
      to {
        transform: translateX(0);
        opacity: 1;
      }
    }
    @keyframes slideOut {
      from {
        transform: translateX(0);
        opacity: 1;
      }
      to {
        transform: translateX(400px);
        opacity: 0;
      }
    }
  `;
  document.head.appendChild(style);
}
